type CopyKey = keyof typeof copy.en;
let locale: 'en' | 'zh-CN' =
  typeof navigator !== 'undefined' && /^zh/i.test(navigator.language) ? 'zh-CN' : 'en';
function t(key: CopyKey, ...values: unknown[]): string {
  return copy[locale][key].replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''));
}
function localizeStatic() {
  document.documentElement.lang = locale;
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as CopyKey);
  });
  for (const attr of ['aria-label', 'placeholder'])
    document
      .querySelectorAll<HTMLElement>(`[data-i18n-${attr}]`)
      .forEach((el) => el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`) as CopyKey)));
}
async function initializeLocale() {
  try {
    const value = await window.pluginBridge?.invoke('app.getLocale');
    if (typeof value === 'string' && value) locale = /^zh/i.test(value) ? 'zh-CN' : 'en';
  } catch {
    /* Browser language is the fallback for static previews and older hosts. */
  }
  localizeStatic();
}
const localeReady = initializeLocale();
