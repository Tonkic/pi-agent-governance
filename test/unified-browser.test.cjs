const { fixture } = require('./pi-fixture.cjs');
const ctx = { sessionId: 'origin' };
const plain = value => JSON.parse(JSON.stringify(value));
const stopped = origin => assert.rejects(fetch(origin + '/panel/'), /fetch failed/);
const safe = reply => { assert.doesNotMatch(JSON.stringify(reply), /#[a-f0-9]{64}|"url"|token/i); };
test('PI uses one real browser service, original calling project and no host Agent/model control', async t => {
  const f = await fixture(t);
  assert.deepEqual([...f.tools.keys()], ['governance', 'governance_ui']);
  assert.equal(f.adapter.onPanelInvoke, undefined); assert.equal(f.opened.length, 0);
  assert.equal((await f.ui.execute({ action: 'status' }, ctx)).result.open, false);
  for (const args of [{ action: 'open' }, { action: 'close' }, { action: 'open', confirmed: 'yes' }, { action: 'open', confirmed: true, url: 'https://example.invalid' }, { action: 'open', confirmed: true, workspace: f.b }])
    assert.equal((await f.ui.execute(args, ctx)).ok, false);
  assert.equal((await f.ui.execute({ action: 'open', confirmed: true })).ok, false);
  assert.equal(f.opened.length, 0);
  const first = await f.ui.execute({ action: 'open', confirmed: true }, ctx);
  assert.equal(first.ok, true, first.error); assert.equal(first.result.workspace, f.a); safe(first);
  assert.equal((await fetch(first.result.origin + '/panel/')).status, 200);
  const again = await f.ui.execute({ action: 'open', confirmed: true }, ctx);
  assert.equal(again.result.origin, first.result.origin); assert.equal(f.opened.length, 2);
  assert.equal(f.opened[0], f.opened[1]); assert.match(f.opened[0], /^http:\/\/127\.0\.0\.1:\d+\/panel\/#[a-f0-9]{64}$/);
  f.session.projectPath = f.b;
  const foreign = await f.ui.execute({ action: 'status' }, ctx);
  assert.deepEqual(plain(foreign.result), { workspace: f.b, origin: null, open: false });
  assert.equal((await f.ui.execute({ action: 'close', confirmed: true }, ctx)).result.closed, false);
  assert.equal((await fetch(first.result.origin + '/panel/')).status, 200);
  const switched = await f.command().run();
  assert.equal(switched.workspace, f.b); safe(switched); await stopped(first.result.origin);
  assert.ok(f.calls.every(call => call.operation === 'session/get'));
  const close = await f.ui.execute({ action: 'close', confirmed: true }, ctx);
  assert.equal(close.result.closed, true); safe(close); await stopped(switched.origin);
});
test('PI workspace change and unload revoke services even when unregister throws', async t => {
  const f = await fixture(t), first = await f.command().run();
  await f.events.get('workspace:changed')(); await stopped(first.origin);
  const second = await f.command().run();
  f.pi.agent.unregisterTool = async name => { f.removed.push(name); throw Error('fixture unregister failure'); };
  await assert.rejects(f.adapter.onUnload(), /unregister failure/);
  await stopped(second.origin);
  assert.ok(f.removed.includes('governance') && f.removed.includes('governance_ui') && f.removed.includes('governance.open'));
  assert.equal(f.events.size, 0);
  assert.equal((await f.ui.execute({ action: 'open', confirmed: true }, ctx)).ok, false);
});
test('PI missing permission/lifecycle and stale asynchronous project identity fail closed', async t => {
  const f = await fixture(t);
  delete f.pi.shell;
  const denied = await f.ui.execute({ action: 'open', confirmed: true }, ctx);
  assert.equal(denied.ok, false); safe(denied);
  assert.equal((await f.ui.execute({ action: 'status' }, ctx)).result.open, false);
  await f.adapter.onUnload(); delete f.pi.events; await f.adapter.onLoad();
  const noEvents = await f.ui.execute({ action: 'open', confirmed: true }, ctx);
  assert.equal(noEvents.ok, false); assert.match(noEvents.error, /lifecycle events/);
  await f.adapter.onUnload();
  f.pi.events = { on: (name, fn) => f.events.set(name, fn), off: name => f.events.delete(name) };
  f.pi.shell = { openExternal: async url => { f.opened.push(url); } };
  await f.adapter.onLoad();
  let release, entered; const waiting = new Promise(resolve => { entered = resolve; });
  f.pi.desktop.invoke = async () => { entered(); await new Promise(resolve => { release = resolve; }); return { session: f.session }; };
  const pending = f.ui.execute({ action: 'open', confirmed: true }, ctx);
  await waiting; await f.events.get('workspace:changed')();
  // Subsequent identity reads are available; release only the old lookup.
  f.pi.desktop.invoke = async () => ({ session: f.session }); release();
  assert.equal((await pending).ok, false); assert.equal(f.opened.length, 0);
});
