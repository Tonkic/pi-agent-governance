test('real MCP tool opens only its bound project, returns no credential and closes on explicit intent', async t => {
  const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
  const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');
  const root = await fs.realpath(await fs.mkdtemp(path.join(process.env.PI_SCRATCH_DIR || os.tmpdir(), 'mcp-ui-')));
  const transport = new StdioClientTransport({ command: process.execPath, args: ['--require', path.resolve('test/mcp-opener-fixture.cjs'), path.resolve('build/mcp/server.js'), '--workspace', root], stderr: 'pipe' });
  let stderr = ''; transport.stderr.on('data', b => { stderr += b; });
  const client = new Client({ name: 'unified-browser-fixture', version: '1' });
  t.after(async () => { await client.close(); await fs.rm(root, { recursive: true, force: true }); });
  await client.connect(transport);
  const call = args => client.callTool({ name: 'governance_ui', arguments: args });
  assert.equal(JSON.parse((await call({ action: 'status' })).content[0].text).open, false);
  assert.equal((await call({ action: 'open' })).isError, true);
  await assert.rejects(call({ action: 'open', confirmed: true, url: 'secret-input' }), e => !e.message.includes('secret-input'));
  const first = await call({ action: 'open', confirmed: true }); assert.ok(!first.isError, first.content[0]?.text); safe(first);
  const opened = JSON.parse(first.content[0].text); assert.equal(opened.workspace, root);
  const repeated = JSON.parse((await call({ action: 'open', confirmed: true })).content[0].text); assert.equal(repeated.origin, opened.origin);
  assert.equal((await fetch(opened.origin + '/panel/')).status, 200); assert.deepEqual(await fs.readdir(root), []);
  const closed = await call({ action: 'close', confirmed: true }); assert.equal(JSON.parse(closed.content[0].text).closed, true); safe(closed); await stopped(opened.origin);
  const final = JSON.parse((await call({ action: 'open', confirmed: true })).content[0].text);
  await client.close(); await stopped(final.origin); assert.equal(stderr, '');
});
test('MCP stdin EOF actually exits and revokes the owned HTTP server without killing it from the harness', { timeout: 15000 }, async t => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(process.env.PI_SCRATCH_DIR || os.tmpdir(), 'mcp-ui-eof-')));
  const child = spawn(process.execPath, ['--require', path.resolve('test/mcp-opener-fixture.cjs'), path.resolve('build/mcp/server.js'), '--workspace', root], { stdio: ['pipe', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) child.kill(); await fs.rm(root, { recursive: true, force: true }); });
  let buffer = '', stderr = ''; const pending = new Map();
  child.stderr.on('data', b => { stderr += b; });
  child.stdout.on('data', b => { buffer += b; let n; while ((n = buffer.indexOf('\n')) >= 0) { const line = buffer.slice(0, n); buffer = buffer.slice(n + 1); const value = JSON.parse(line); pending.get(value.id)?.(value); pending.delete(value.id); } });
  const rpc = (id, method, params) => new Promise(resolve => { pending.set(id, resolve); child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n'); });
  await rpc(1, 'initialize', { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'eof-fixture', version: '1' } });
  child.stdin.write('{"jsonrpc":"2.0","method":"notifications/initialized"}\n');
  const reply = await rpc(2, 'tools/call', { name: 'governance_ui', arguments: { action: 'open', confirmed: true } });
  assert.ok(!reply.result.isError, reply.result.content[0]?.text); safe(reply);
  const { origin } = JSON.parse(reply.result.content[0].text);
  const exit = new Promise(resolve => child.once('exit', (code, signal) => resolve({ code, signal })));
  child.stdin.end();
  assert.deepEqual(await exit, { code: 0, signal: null }); await stopped(origin); assert.equal(stderr, '');
});
