'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { chromium } = require('playwright');
const { startConsole } = require('../build/web/server');
const { Governance } = require('../build/plugin/core');
(async () => {
  const root = await fs.mkdtemp(path.join(process.env.PI_SCRATCH_DIR || os.tmpdir(), 'web-browser-'));
  const screenshots = path.join(process.env.PI_SCREENSHOT_DIR || process.env.PI_SCRATCH_DIR || os.tmpdir(), 'http-console');
  await fs.mkdir(screenshots, { recursive: true });
  const g = new Governance(root);
  await g.run({ action: 'init' });
  await g.run({ action: 'start', id: 'web-ui', goal: 'Local browser project control', criteria: ['Real HTTP browser interactions'] });
  const app = await startConsole({ workspace: root });
  const browser = await chromium.launch({ headless: true, ...(process.env.PI_BROWSER ? { executablePath: process.env.PI_BROWSER } : {}) });
  let page;
  try {
    const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 900 } });
    page = await context.newPage();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const confirm = async (yes = true) => { await page.locator('#confirm-dialog').waitFor({ state: 'visible' }); await page.locator(`#confirm-dialog button[value="${yes ? 'confirm' : 'cancel'}"]`).click(); };
    const ready = async () => { await page.waitForFunction(() => document.querySelector('#board-section').getAttribute('aria-busy') === 'false' && !document.querySelector('#refresh').disabled); };
    await page.goto(app.url); await ready();
    assert.ok(!page.url().includes(app.url.split('#')[1]), 'Token removed from address bar');
    await page.locator('#local-console-info').waitFor();
    for (const id of ['analysis-start', 'architecture-analyze', 'documentation-start', 'operations-open', 'design-start']) assert.equal(await page.locator('#' + id).isVisible(), false, id);
    assert.deepEqual(errors, []);
    await page.locator('a[href="#board-section"]').click();
    await page.locator('#board-new').click(); await page.locator('#workitem-title').fill('网页创建 · Shared task');
    await page.locator('#workitem-description').fill('<img src=x onerror=alert(1)> 这是文本');
    await page.locator('#workitem-save').click(); await confirm(false);
    assert.equal((await g.run({ action: 'project_snapshot' })).board.items.length, 0);
    await page.locator('#workitem-save').click(); await confirm();
    await page.waitForFunction(() => document.querySelectorAll('[data-workitem]').length === 1);
    const first = (await g.run({ action: 'project_snapshot' })).board.items[0];
    assert.equal(first.title, '网页创建 · Shared task');
    await page.locator(`[data-workitem="${first.id}"]`).click();
    assert.match(await page.locator('#item-description').textContent(), /<img src=x/);
    assert.equal(await page.locator('#item-description img').count(), 0);
    await page.locator('#item-close').click();
    await page.locator('#project-open').click(); await page.locator('#edit-current').fill('Updated from the browser');
    await page.locator('#progress-form button[type="submit"]').click(); await confirm();
    await page.waitForFunction(() => document.querySelector('#current').textContent === 'Updated from the browser');
    assert.equal((await g.run({ action: 'status' })).current, 'Updated from the browser');
    await page.locator('#project-close').click();
    let p = await g.run({ action: 'project_snapshot' });
    await g.run({ action: 'board_create', id: 'external', title: 'MCP external update', expectedRevision: p.revision });
    await page.locator('#refresh').click(); await ready();
    assert.equal(await page.locator('[data-workitem="external"]').count(), 1);
    // Existing open forms must not overwrite a newer client's project revision.
    await page.locator('#board-new').click(); await page.locator('#workitem-title').fill('Stale browser draft');
    p = await g.run({ action: 'project_snapshot' });
    await g.run({ action: 'board_update', id: 'external', title: 'New external title', expectedRevision: p.revision });
    await page.locator('#workitem-save').click(); await confirm();
    await page.waitForFunction(() => document.querySelector('#notice').classList.contains('error'));
    assert.equal((await g.run({ action: 'project_snapshot' })).board.items.length, 2);
    await page.locator('#workitem-cancel').click();
    if (await page.locator('#confirm-dialog').isVisible()) await confirm();
    await page.waitForFunction(() => !document.querySelector('#item-sheet').open);
    await page.locator('a[href="#architecture"]').click(); await page.locator('#show-design').click();
    await page.locator('#refresh').click(); await ready(); await page.locator('#show-design').click();
    await page.locator('#design-begin').click(); await page.locator('#design-reason').fill('Explicit browser design draft');
    await page.locator('#design-begin-submit').click(); await confirm();
    await page.waitForFunction(() => !document.querySelector('#design-begin-dialog').open);
    await ready();
    let design = await g.run({ action: 'architecture_design_snapshot' });
    await g.run({ action: 'architecture_design_save', expectedRevision: design.revision, expectedDraft: design.draft.draftId, proposal: { title: 'Client-saved design', document: 'Intent only, not implementation or test evidence.', nodes: [{ id: 'console', title: 'Console', description: 'Project control', files: [] }], edges: [] } });
    await page.locator('#refresh').click(); await ready(); await page.locator('#show-design').click();
    await page.locator('#design-review').click(); await page.locator('#design-reviewer').fill('Browser reviewer');
    await page.locator('#design-conclusion').fill('Reviewed intent and structure'); await page.locator('#design-reviewed').check();
    await page.locator('#design-confirm-submit').click(); await confirm();
    await page.waitForFunction(() => !document.querySelector('#design-confirm-dialog').open);
    await ready();
    assert.equal((await g.run({ action: 'architecture_design_snapshot' })).baseline.number, 1);
    await page.locator('#behavior-docs-open').click(); await page.locator('#behavior-docs-status').waitFor();
    assert.equal(await page.locator('#behavior-docs-dialog').isVisible(), true); await page.locator('#behavior-docs-close').click();
    for (const width of [390, 768, 1280]) for (const mode of ['light', 'dark']) {
      await page.setViewportSize({ width, height: 900 }); await page.emulateMedia({ colorScheme: mode });
      await page.locator('a[href="#board-section"]').click();
      await page.waitForFunction(expected => document.documentElement.dataset.base === expected, mode);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.screenshot({ path: path.join(screenshots, `console-zh-${width}-${mode}.png`) });
    }
    await page.reload(); await ready(); assert.equal(await page.locator('[data-workitem]').count(), 2, 'Tab session survives reload');
    const english = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 900 } });
    const en = await english.newPage(); await en.goto(app.url);
    await en.waitForFunction(() => document.querySelector('#board-section').getAttribute('aria-busy') === 'false');
    assert.match(await en.locator('#local-console-info').textContent(), /Local project console/);
    await en.screenshot({ path: path.join(screenshots, 'console-en-desktop.png') });
    await english.close();
    const disconnected = await browser.newContext({ locale: 'en-US' }); const lost = await disconnected.newPage(); await lost.goto(app.origin + '/panel/');
    await lost.waitForFunction(() => document.querySelector('#notice').classList.contains('error'));
    assert.match(await lost.locator('#notice').textContent(), /private URL/); await disconnected.close();
    assert.deepEqual(errors, []);
    await require('./reference-ui-browser.cjs')({ browser, screenshots });
    await require('./documents-browser.cjs')({ browser, screenshots });
    console.log(`PASS real local HTTP console: confirmations, shared updates, stale writes, design review, docs, session reload, disconnected state, bilingual responsive/themes; 7 screenshots: ${screenshots}`);
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(screenshots, 'failure.png') }).catch(() => {});
    throw error;
  } finally { await browser.close(); await app.close(); await fs.rm(root, { recursive: true, force: true, maxRetries: 5 }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
